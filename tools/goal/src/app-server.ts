export interface AppServer {
  endpoint?: string;
  identity?: ProcessIdentity | undefined;
  request<T = any>(method: string, params: unknown): Promise<T>;
  onNotification(listener: (notification: Notification) => void): () => void;
  detach?(): void | Promise<void>;
  close(): void | Promise<void>;
}

/** Whether a process group still has a member; a dead leader's helpers keep their group alive. */
function groupExists(pid: number): boolean {
  try {
    process.kill(-pid, 0);
    return true;
  } catch (error) {
    return (error as NodeJS.ErrnoException).code !== 'ESRCH';
  }
}

function signalGroup(pid: number, signal: NodeJS.Signals): void {
  try {
    process.kill(-pid, signal);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ESRCH') throw error;
  }
}

/** Ends a detached app-server group and its helpers and thread writers. */
async function stopGroup(child: ChildProcess, graceMs: number): Promise<void> {
  const pid = child.pid;
  if (!pid) return;
  if (!groupExists(pid)) return stopChild(child, graceMs);
  const groupGone = async (ms: number) => {
    const deadline = Date.now() + ms;
    while (groupExists(pid) && Date.now() < deadline)
      await new Promise((resolve) => setTimeout(resolve, defaultPolicy.appServer.exitPollMs));
    return !groupExists(pid);
  };
  signalGroup(pid, 'SIGTERM');
  if (await groupGone(graceMs)) return;
  signalGroup(pid, 'SIGKILL');
  await groupGone(defaultPolicy.appServer.killWaitMs);
}

async function stopChild(child: ChildProcess, graceMs: number, group = false): Promise<void> {
  if (!child.pid) return;
  if (group) return stopGroup(child, graceMs);
  if (child.exitCode !== null || child.signalCode !== null) return;
  const exited = new Promise<void>((resolve) => child.once('exit', () => resolve()));
  child.kill('SIGTERM');
  let timer: ReturnType<typeof setTimeout> | undefined;
  const stopped = await Promise.race([
    exited.then(() => true),
    new Promise<boolean>((resolve) => {
      timer = setTimeout(() => resolve(false), graceMs);
    }),
  ]);
  clearTimeout(timer);
  if (!stopped) {
    if (child.exitCode === null && child.signalCode === null) child.kill('SIGKILL');
    await exited;
  }
}

/**
 * Newline-delimited JSON-RPC, as generated by codex-cli 0.163.0. Stdio child ownership remains local to this client.
 */
export class StdioAppServer implements AppServer {
  private readonly child: ChildProcessWithoutNullStreams;
  private readonly rpc: AppServerRpc;
  constructor(
    argv: readonly string[],
    env: NodeJS.ProcessEnv,
    timeoutMs = defaultPolicy.appServer.requestTimeoutMs,
    private readonly terminationGraceMs = defaultPolicy.appServer.terminationGraceMs,
  ) {
    this.child = spawn(argv[0]!, argv.slice(1), { env, stdio: 'pipe' });
    this.rpc = new AppServerRpc((text) => this.child.stdin.write(`${text}\n`), timeoutMs);
    this.child.stderr.on('data', () => {});
    createInterface({ input: this.child.stdout }).on('line', (line) => this.rpc.receive(line));
    this.child.on('error', (error) => this.rpc.fail(error));
    this.child.on('exit', (code, signal) => this.rpc.fail(new Error(`App-server exited (${code ?? signal})`)));
    this.child.stdin.on('error', (error) => this.rpc.fail(error));
  }
  get identity(): ProcessIdentity | undefined {
    return this.child.pid ? (readProcessIdentity(this.child.pid) ?? undefined) : undefined;
  }
  async initialize(): Promise<void> {
    await this.rpc.initialize();
  }
  request<T = any>(method: string, params: unknown): Promise<T> {
    return this.rpc.request(method, params);
  }
  onNotification(listener: (notification: Notification) => void): () => void {
    return this.rpc.onNotification(listener);
  }
  close(): void | Promise<void> {
    this.rpc.fail(new Error('App-server client closed'));
    return stopChild(this.child, this.terminationGraceMs);
  }
}

const APP_SERVER_READY = /readyz:\s*(https?:\/\/127\.0\.0\.1:\d+\/readyz)/;

/** Installed `codex-cli 0.164.0` colors `readyz:` with CSI; strip it before matching. */
function stripAnsi(text: string): string {
  return text.replace(/\x1b\[[0-9;]*[A-Za-z]/g, '');
}

function retainAppServerDiagnostics(current: string, chunk: string, limit: number): string {
  const next = current + chunk;
  return next.length <= limit ? next : next.slice(-limit);
}

export type CodexPool = { id: string; codexHome: string; executable?: string };

/** Private identity data needed to attach a replacement Goal host to the exact pool process. */
export type AppServerAttachment = {
  version: 1;
  identity: ProcessIdentity;
  poolId: string;
  codexHome: string;
  executable: string;
  endpoint: string;
  environmentFingerprint: string;
  selectedExecutablePath: string;
  selectedExecutableDevice: number;
  selectedExecutableInode: number;
  processExecutablePath: string;
  processExecutableDevice: number;
  processExecutableInode: number;
};

export function appServerEnvironment(pool: CodexPool, parent: NodeJS.ProcessEnv = process.env): NodeJS.ProcessEnv {
  const env: NodeJS.ProcessEnv = {
    ...cleanManagedProviderEnvironment(parent),
    CODEX_HOME: pool.codexHome,
    NO_COLOR: '1',
    TERM: 'dumb',
  };
  delete env.FORCE_COLOR;
  delete env.CLICOLOR_FORCE;
  return env;
}

/** Hash all inherited provider environment values without placing any credential in the registry. */
export function appServerEnvironmentFingerprint(pool: CodexPool, parent: NodeJS.ProcessEnv = process.env): string {
  const sorted = Object.entries(appServerEnvironment(pool, parent)).sort(([left], [right]) =>
    left.localeCompare(right),
  );
  return createHash('sha256').update(JSON.stringify(sorted)).digest('hex');
}

export function selectedAppServerExecutable(pool: CodexPool, pathValue = process.env.PATH ?? ''): string {
  const executable = pool.executable ?? 'codex';
  const candidates =
    isAbsolute(executable) || executable.includes('/')
      ? [resolve(executable)]
      : pathValue
          .split(delimiter)
          .filter(Boolean)
          .map((directory) => join(directory, executable));
  for (const candidate of candidates) {
    try {
      accessSync(candidate, constants.X_OK);
      return realpathSync(candidate);
    } catch {}
  }
  throw new Error(`Cannot resolve app-server executable: ${executable}`);
}

/** Accept only the literal loopback endpoint emitted by `codex app-server --listen ws://127.0.0.1:0`. */
export function isPrivateAppServerEndpoint(endpoint: string): boolean {
  if (!/^ws:\/\/127\.0\.0\.1:[1-9]\d{0,4}$/.test(endpoint)) return false;
  try {
    const parsed = new URL(endpoint);
    return (
      parsed.protocol === 'ws:' &&
      parsed.hostname === '127.0.0.1' &&
      parsed.port !== '' &&
      Number(parsed.port) > 0 &&
      Number(parsed.port) <= 65535 &&
      parsed.username === '' &&
      parsed.password === '' &&
      (parsed.pathname === '' || parsed.pathname === '/') &&
      parsed.search === '' &&
      parsed.hash === ''
    );
  } catch {
    return false;
  }
}

export class ForeignAppServerEndpointError extends Error {
  constructor(endpoint: string) {
    super(`Recorded loopback endpoint is not owned by its app-server process: ${endpoint}`);
    this.name = 'ForeignAppServerEndpointError';
  }
}

/** Check the listening TCP socket inode against the recorded process's open descriptors. */
export function appServerEndpointOwnership(
  identity: ProcessIdentity,
  endpoint: string,
): 'owned' | 'unavailable' | 'foreign' {
  if (!isPrivateAppServerEndpoint(endpoint)) return 'foreign';
  const port = Number(new URL(endpoint).port);
  const portHex = port.toString(16).toUpperCase().padStart(4, '0');
  let listenerInode: string | undefined;
  try {
    for (const line of readFileSync(`/proc/${identity.pid}/net/tcp`, 'utf8').split('\n').slice(1)) {
      const columns = line.trim().split(/\s+/);
      if (columns.length < 10 || columns[3] !== '0A') continue;
      const [address, localPort] = columns[1]!.split(':');
      if (address?.toUpperCase() === '0100007F' && localPort?.toUpperCase() === portHex) {
        listenerInode = columns[9];
        break;
      }
    }
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT' && !sameProcess(identity)) return 'unavailable';
    throw error;
  }
  if (!listenerInode) return 'unavailable';

  try {
    for (const descriptor of readdirSync(`/proc/${identity.pid}/fd`)) {
      try {
        if (readlinkSync(`/proc/${identity.pid}/fd/${descriptor}`) === `socket:[${listenerInode}]`) return 'owned';
      } catch (error) {
        if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
      }
    }
    return 'foreign';
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code === 'ENOENT' && !sameProcess(identity)) return 'unavailable';
    throw error;
  }
}

/** JSON-RPC over the loopback WebSocket app-server owned by a manager host or adopted from its predecessor. */
export class WebSocketAppServer implements AppServer {
  private readonly rpc: AppServerRpc;
  private detached = false;
  constructor(
    readonly endpoint: string,
    private readonly socket: WebSocket,
    private readonly child: ChildProcess | undefined,
    private readonly processIdentity: ProcessIdentity,
    timeoutMs = defaultPolicy.appServer.requestTimeoutMs,
    private readonly terminationGraceMs = defaultPolicy.appServer.terminationGraceMs,
  ) {
    this.rpc = new AppServerRpc((text) => {
      if (this.socket.readyState !== WebSocket.OPEN) {
        throw this.rpc.terminalError ?? new Error('App-server WebSocket is not open');
      }
      this.socket.send(text);
    }, timeoutMs);
    socket.addEventListener('message', (event) => {
      this.rpc.receive(typeof event.data === 'string' ? event.data : String(event.data));
    });
    socket.addEventListener('error', () => this.rpc.fail(new Error('App-server WebSocket failed')));
    socket.addEventListener('close', () => this.rpc.fail(new Error('App-server WebSocket closed')));
    child?.on('error', (error) => this.rpc.fail(error));
    child?.on('exit', (code, signal) => this.rpc.fail(new Error(`App-server exited (${code ?? signal})`)));
  }
  get identity(): ProcessIdentity | undefined {
    return this.processIdentity;
  }
  async initialize(): Promise<void> {
    await this.rpc.initialize();
  }
  request<T = any>(method: string, params: unknown): Promise<T> {
    return this.rpc.request(method, params);
  }
  onNotification(listener: (notification: Notification) => void): () => void {
    return this.rpc.onNotification(listener);
  }
  async detach(): Promise<void> {
    if (this.detached) return;
    this.detached = true;
    this.rpc.fail(new Error('App-server client detached'));
    try {
      this.socket.close();
    } catch {}
    this.child?.stdout?.destroy();
    this.child?.stderr?.destroy();
    this.child?.unref();
  }
  async close(): Promise<void> {
    if (!this.detached) {
      this.detached = true;
      this.rpc.fail(new Error('App-server client closed'));
      try {
        this.socket.close();
      } catch {}
    }
    if (this.child) await stopChild(this.child, this.terminationGraceMs, true);
  }
}

async function waitForAppServerReady(
  child: ChildProcess,
  policy: ControlPolicy['appServer'],
  diagnosticsPath?: string,
): Promise<string> {
  let stderr = '';
  let settled = false;
  return new Promise<string>((resolveReady, reject) => {
    let poll: ReturnType<typeof setInterval> | undefined;
    const finish = (error?: Error, value?: string) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      if (poll) clearInterval(poll);
      child.stderr?.removeListener('data', onData);
      child.removeListener('error', onError);
      child.removeListener('exit', onExit);
      if (error) reject(error);
      else resolveReady(value!);
    };
    const observe = (text: string) => {
      stderr = retainAppServerDiagnostics(stderr, text, policy.diagnosticCharacters);
      const match = stripAnsi(stderr).match(APP_SERVER_READY);
      if (match) finish(undefined, match[1]);
    };
    const onData = (chunk: Buffer | string) => observe(String(chunk));
    const onError = (error: Error) => finish(error);
    const onExit = (code: number | null, signal: NodeJS.Signals | null) =>
      finish(new Error(`App-server exited before readiness (${code ?? signal}): ${stderr}`));
    const timer = setTimeout(
      () => finish(new Error(`Timed out waiting for app-server readiness: ${stderr}`)),
      policy.readinessTimeoutMs,
    );
    child.on('error', onError);
    child.on('exit', onExit);
    if (diagnosticsPath) {
      const readLog = () => {
        try {
          const data = readFileSync(diagnosticsPath, 'utf8');
          observe(data.slice(-policy.diagnosticCharacters));
        } catch (error) {
          if ((error as NodeJS.ErrnoException).code !== 'ENOENT') finish(error as Error);
        }
      };
      poll = setInterval(readLog, Math.min(policy.exitPollMs, 50));
      readLog();
    } else if (child.stderr) child.stderr.on('data', onData);
    else finish(new Error('App-server diagnostics stream is unavailable'));
  });
}

async function openAppServerSocket(endpoint: string, policy: ControlPolicy['appServer']): Promise<WebSocket> {
  const socket = new WebSocket(endpoint);
  try {
    await new Promise<void>((resolveReady, reject) => {
      const finish = (error?: Error) => {
        clearTimeout(timer);
        socket.removeEventListener('open', onOpen);
        socket.removeEventListener('error', onError);
        if (error) reject(error);
        else resolveReady();
      };
      const timer = setTimeout(
        () => finish(new Error(`Timed out connecting to app-server at ${endpoint}`)),
        policy.connectTimeoutMs,
      );
      const onOpen = () => finish();
      const onError = () => finish(new Error(`Cannot connect to app-server at ${endpoint}`));
      socket.addEventListener('open', onOpen, { once: true });
      socket.addEventListener('error', onError, { once: true });
    });
    return socket;
  } catch (error) {
    socket.close();
    throw error;
  }
}

export function connectPool(
  pool: CodexPool,
  onStart?: (identity: ProcessIdentity) => void,
  parentEnvironment?: NodeJS.ProcessEnv,
  policy?: ControlPolicy['appServer'],
  diagnosticsPath?: string,
): Promise<WebSocketAppServer>;

/** Starts one loopback app-server owned by this process and connects its JSON-RPC WebSocket. */
export async function connectPool(
  pool: CodexPool,
  onStart?: (identity: ProcessIdentity) => void,
  parentEnvironment: NodeJS.ProcessEnv = process.env,
  policy = defaultPolicy.appServer,
  diagnosticsPath?: string,
): Promise<WebSocketAppServer> {
  const executable = pool.executable ?? 'codex';
  const env = appServerEnvironment(pool, parentEnvironment);
  // The app-server leads its own process group, so its helpers and thread writers form one unit that a replacement
  // host can reclaim after a failed handoff; detached log output also lets a graceful host handoff close its pipes.
  let child: ChildProcess;
  if (diagnosticsPath) {
    mkdirSync(dirname(diagnosticsPath), { recursive: true });
    const descriptor = openSync(diagnosticsPath, 'w', 0o600);
    try {
      chmodSync(diagnosticsPath, 0o600);
      child = spawn(executable, ['app-server', '--listen', 'ws://127.0.0.1:0'], {
        env,
        stdio: ['ignore', descriptor, descriptor],
        detached: true,
      });
    } finally {
      closeSync(descriptor);
    }
  } else {
    child = spawn(executable, ['app-server', '--listen', 'ws://127.0.0.1:0'], {
      env,
      stdio: 'pipe',
      detached: true,
    });
  }
  if (onStart) {
    const identity = child.pid ? readProcessIdentity(child.pid) : null;
    if (!child.pid) throw new Error('Cannot start app-server process');
    if (!identity) {
      await stopChild(child, policy.terminationGraceMs, true);
      throw new Error('Cannot identify app-server process');
    }
    try {
      onStart(identity);
    } catch (error) {
      await stopChild(child, policy.terminationGraceMs, true);
      throw error;
    }
  }
  child.stdout?.resume();
  const identity = child.pid ? readProcessIdentity(child.pid) : null;
  if (!identity) {
    await stopChild(child, policy.terminationGraceMs, true);
    throw new Error('Cannot identify app-server process');
  }
  child.unref();
  try {
    const readiness = await waitForAppServerReady(child, policy, diagnosticsPath);
    const endpoint = readiness.replace(/^https?:/, 'ws:').replace(/\/readyz$/, '');
    if (!isPrivateAppServerEndpoint(endpoint)) throw new Error(`Refusing non-private app-server endpoint: ${endpoint}`);
    const socket = await openAppServerSocket(endpoint, policy);
    const client = new WebSocketAppServer(
      endpoint,
      socket,
      child,
      identity,
      policy.requestTimeoutMs,
      policy.terminationGraceMs,
    );
    try {
      await client.initialize();
      return client;
    } catch (error) {
      await client.close();
      throw error;
    }
  } catch (error) {
    await stopChild(child, policy.terminationGraceMs, true);
    throw error;
  }
}

/** Reconnect to a recorded same-pool server without taking ownership of or stopping its process group. */
export async function attachPool(
  pool: CodexPool,
  attachment: AppServerAttachment,
  policy = defaultPolicy.appServer,
  parentEnvironment: NodeJS.ProcessEnv = process.env,
): Promise<WebSocketAppServer> {
  if (
    attachment.version !== 1 ||
    attachment.poolId !== pool.id ||
    attachment.codexHome !== pool.codexHome ||
    attachment.executable !== (pool.executable ?? 'codex')
  )
    throw new Error('Refusing app-server attachment for a different manager pool');
  if (!isPrivateAppServerEndpoint(attachment.endpoint))
    throw new Error(`Refusing non-private app-server endpoint: ${attachment.endpoint}`);
  if (attachment.environmentFingerprint !== appServerEnvironmentFingerprint(pool, parentEnvironment))
    throw new Error('Manager pool app-server environment changed');
  if (!sameProcess(attachment.identity)) throw new Error('Recorded manager app-server process is no longer alive');
  if (appServerEndpointOwnership(attachment.identity, attachment.endpoint) === 'foreign')
    throw new ForeignAppServerEndpointError(attachment.endpoint);
  const socket = await openAppServerSocket(attachment.endpoint, policy);
  if (appServerEndpointOwnership(attachment.identity, attachment.endpoint) === 'foreign') {
    socket.close();
    throw new ForeignAppServerEndpointError(attachment.endpoint);
  }
  const client = new WebSocketAppServer(
    attachment.endpoint,
    socket,
    undefined,
    attachment.identity,
    policy.requestTimeoutMs,
  );
  try {
    await client.initialize();
    return client;
  } catch (error) {
    await client.detach();
    throw error;
  }
}

