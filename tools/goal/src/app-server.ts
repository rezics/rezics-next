// JSON-RPC's protocol-defined error code for unsupported methods.
const METHOD_NOT_FOUND = -32601;

export type Notification = { method: string; params: any };
export interface AppServer {
  endpoint?: string;
  identity?: ProcessIdentity | undefined;
  request<T = any>(method: string, params: unknown): Promise<T>;
  onNotification(listener: (notification: Notification) => void): () => void;
  close(): void | Promise<void>;
}
export class RpcError extends Error {
  constructor(
    readonly code: number,
    message: string,
    readonly data?: unknown,
  ) {
    super(message);
  }
}

async function stopChild(child: ChildProcessWithoutNullStreams, graceMs: number): Promise<void> {
  if (!child.pid) return;
  if (child.exitCode !== null || child.signalCode !== null) return;
  const exited = new Promise<void>((resolve) => child.once('exit', () => resolve()));
  child.kill('SIGTERM');
  let timer: ReturnType<typeof setTimeout> | undefined;
  const stopped = await Promise.race([
    exited.then(() => true),
    new Promise<boolean>((resolve) => {
      timer = setTimeout(() => resolve(false), graceMs);
    }),
  ]);
  clearTimeout(timer);
  if (!stopped) {
    if (child.exitCode === null && child.signalCode === null) child.kill('SIGKILL');
    await exited;
  }
}

/** Newline-delimited JSON-RPC, as generated by codex-cli 0.163.0. */
export class StdioAppServer implements AppServer {
  private readonly child: ChildProcessWithoutNullStreams;
  private nextId = 0;
  private pending = new Map<
    number,
    { resolve(value: any): void; reject(error: Error): void; timer: ReturnType<typeof setTimeout> }
  >();
  private listeners = new Set<(notification: Notification) => void>();
  private ended: Error | undefined;
  constructor(
    argv: readonly string[],
    env: NodeJS.ProcessEnv,
    private readonly timeoutMs = defaultPolicy.appServer.requestTimeoutMs,
    private readonly terminationGraceMs = defaultPolicy.appServer.terminationGraceMs,
  ) {
    this.child = spawn(argv[0]!, argv.slice(1), { env, stdio: 'pipe' });
    this.child.stderr.on('data', () => {});
    createInterface({ input: this.child.stdout }).on('line', (line) => {
      try {
        this.receive(JSON.parse(line));
      } catch (error) {
        this.fail(new Error(`Invalid app-server message: ${error}`));
      }
    });
    this.child.on('error', (error) => this.fail(error));
    this.child.on('exit', (code, signal) => this.fail(new Error(`App-server exited (${code ?? signal})`)));
    this.child.stdin.on('error', (error) => this.fail(error));
  }
  get identity(): ProcessIdentity | undefined {
    return this.child.pid ? (readProcessIdentity(this.child.pid) ?? undefined) : undefined;
  }
  private receive(message: any): void {
    if (message.method && message.id !== undefined) {
      // This client never grants tool approvals on behalf of the maintainer.
      this.write({
        id: message.id,
        error: { code: METHOD_NOT_FOUND, message: `Unsupported server request: ${message.method}` },
      });
    } else if (message.method) {
      for (const listener of this.listeners) listener(message);
    } else {
      const pending = this.pending.get(message.id);
      if (!pending) return;
      this.pending.delete(message.id);
      clearTimeout(pending.timer);
      if (message.error) pending.reject(new RpcError(message.error.code, message.error.message, message.error.data));
      else pending.resolve(message.result);
    }
  }
  private write(message: unknown): void {
    this.child.stdin.write(`${JSON.stringify(message)}\n`);
  }
  private fail(error: Error): void {
    this.ended = error;
    for (const pending of this.pending.values()) {
      clearTimeout(pending.timer);
      pending.reject(error);
    }
    this.pending.clear();
  }
  async initialize(): Promise<void> {
    await this.request('initialize', {
      clientInfo: { name: 'rezics_goal', title: 'REZICS Goal', version: '0.1.0' },
      capabilities: { experimentalApi: true, requestAttestation: false },
    });
    this.write({ method: 'initialized' });
  }
  request<T = any>(method: string, params: unknown): Promise<T> {
    if (this.ended) return Promise.reject(this.ended);
    const id = ++this.nextId;
    return new Promise<T>((resolve, reject) => {
      const timer = setTimeout(() => {
        this.pending.delete(id);
        reject(new Error(`App-server request timed out: ${method}`));
      }, this.timeoutMs);
      this.pending.set(id, { resolve, reject, timer });
      this.write({ id, method, params });
    });
  }
  onNotification(listener: (notification: Notification) => void): () => void {
    this.listeners.add(listener);
    return () => this.listeners.delete(listener);
  }
  close(): void | Promise<void> {
    this.fail(new Error('App-server client closed'));
    return stopChild(this.child, this.terminationGraceMs);
  }
}

const APP_SERVER_READY = /readyz:\s*(https?:\/\/127\.0\.0\.1:\d+\/readyz)/;

/** Installed `codex-cli 0.164.0` colors `readyz:` with CSI; strip it before matching. */
function stripAnsi(text: string): string {
  return text.replace(/\x1b\[[0-9;]*[A-Za-z]/g, '');
}

function retainAppServerDiagnostics(current: string, chunk: string, limit: number): string {
  const next = current + chunk;
  return next.length <= limit ? next : next.slice(-limit);
}

