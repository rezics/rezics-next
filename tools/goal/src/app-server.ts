/** JSON-RPC over the WebSocket app-server owned by this manager host. */
export class WebSocketAppServer implements AppServer {
  private readonly rpc: AppServerRpc;
  constructor(
    readonly endpoint: string,
    private readonly socket: WebSocket,
    private readonly child: ChildProcessWithoutNullStreams,
    timeoutMs = defaultPolicy.appServer.requestTimeoutMs,
    private readonly terminationGraceMs = defaultPolicy.appServer.terminationGraceMs,
  ) {
    this.rpc = new AppServerRpc((text) => {
      if (this.socket.readyState !== WebSocket.OPEN) {
        throw this.rpc.terminalError ?? new Error('App-server WebSocket is not open');
      }
      this.socket.send(text);
    }, timeoutMs);
    socket.addEventListener('message', (event) => {
      this.rpc.receive(typeof event.data === 'string' ? event.data : String(event.data));
    });
    socket.addEventListener('error', () => this.rpc.fail(new Error('App-server WebSocket failed')));
    socket.addEventListener('close', () => this.rpc.fail(new Error('App-server WebSocket closed')));
    child.on('error', (error) => this.rpc.fail(error));
    child.on('exit', (code, signal) => this.rpc.fail(new Error(`App-server exited (${code ?? signal})`)));
  }
  get identity(): ProcessIdentity | undefined {
    return this.child.pid ? (readProcessIdentity(this.child.pid) ?? undefined) : undefined;
  }
  async initialize(): Promise<void> {
    await this.rpc.initialize();
  }
  request<T = any>(method: string, params: unknown): Promise<T> {
    return this.rpc.request(method, params);
  }
  onNotification(listener: (notification: Notification) => void): () => void {
    return this.rpc.onNotification(listener);
  }
  close(): void | Promise<void> {
    this.rpc.fail(new Error('App-server client closed'));
    try {
      this.socket.close();
    } catch {}
    return stopChild(this.child, this.terminationGraceMs, true);
  }
}

