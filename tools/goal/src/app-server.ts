/** Starts one loopback app-server owned by this process and connects its JSON-RPC WebSocket. */
export async function connectPool(
  pool: CodexPool,
  onStart?: (identity: ProcessIdentity) => void,
  parentEnvironment: NodeJS.ProcessEnv = process.env,
  policy = defaultPolicy.appServer,
): Promise<WebSocketAppServer> {
  const executable = pool.executable ?? 'codex';
  const env: NodeJS.ProcessEnv = {
    ...cleanManagedProviderEnvironment(parentEnvironment),
    CODEX_HOME: pool.codexHome,
    NO_COLOR: '1',
    TERM: 'dumb',
  };
  delete env.FORCE_COLOR;
  delete env.CLICOLOR_FORCE;
  // The app-server leads its own process group, so its helpers and thread writers form one unit that a replacement host
  // can reclaim after this host dies; the group id is the app-server's pid (see stopGroup).
  const child = spawn(executable, ['app-server', '--listen', 'ws://127.0.0.1:0'], {
    env,
    stdio: 'pipe',
    detached: true,
  });
  if (onStart) {
    const identity = child.pid ? readProcessIdentity(child.pid) : null;
    if (!child.pid) throw new Error('Cannot start app-server process');
    if (!identity) {
      await stopChild(child, policy.terminationGraceMs, true);
      throw new Error('Cannot identify app-server process');
    }
    try {
      onStart(identity);
    } catch (error) {
      await stopChild(child, policy.terminationGraceMs, true);
      throw error;
    }
  }
  child.stdout.resume();
  let stderr = '';
  let settled = false;
  const ready = new Promise<string>((resolveReady, reject) => {
    const finish = (error?: Error, value?: string) => {
      if (settled) return;
      settled = true;
      clearTimeout(timer);
      if (error) reject(error);
      else resolveReady(value!);
    };
    const timer = setTimeout(
      () => finish(new Error(`Timed out waiting for app-server readiness: ${stderr}`)),
      policy.readinessTimeoutMs,
    );
    child.stderr.on('data', (chunk) => {
      if (settled) return;
      stderr = retainAppServerDiagnostics(stderr, String(chunk), policy.diagnosticCharacters);
      const match = stripAnsi(stderr).match(APP_SERVER_READY);
      if (match) finish(undefined, match[1]);
    });
    child.on('error', (error) => finish(error));
    child.on('exit', (code, signal) =>
      finish(new Error(`App-server exited before readiness (${code ?? signal}): ${stderr}`)),
    );
  });
  try {
    const readiness = await ready;
    const endpoint = readiness.replace(/^https?:/, 'ws:').replace(/\/readyz$/, '');
    const socket = new WebSocket(endpoint);
    await new Promise<void>((resolveReady, reject) => {
      const timer = setTimeout(() => {
        socket.close();
        reject(new Error(`Timed out connecting to app-server at ${endpoint}`));
      }, policy.connectTimeoutMs);
      socket.addEventListener(
        'open',
        () => {
          clearTimeout(timer);
          resolveReady();
        },
        { once: true },
      );
      socket.addEventListener(
        'error',
        () => {
          clearTimeout(timer);
          reject(new Error(`Cannot connect to app-server at ${endpoint}`));
        },
        { once: true },
      );
    });
    const client = new WebSocketAppServer(endpoint, socket, child, policy.requestTimeoutMs, policy.terminationGraceMs);
    try {
      await client.initialize();
      return client;
    } catch (error) {
      await client.close();
      throw error;
    }
  } catch (error) {
    await stopChild(child, policy.terminationGraceMs, true);
    throw error;
  }
}

