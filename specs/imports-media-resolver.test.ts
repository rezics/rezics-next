const uuid = (n: number) => `00000000-0000-8000-8000-${n.toString(16).padStart(12, '0')}`;
const CONTAINER = uuid(1);
const OWNER: Owner = { source: 'bangumi', external_id: '42' };
const URL = 'https://lain.bgm.tv/pic/cover/l/ab/cd/42.jpg';
function conversion(o = OWNER, url = URL, version: string | null = 'native:7', converterRevision = 'cover-v1') {
  return convertBangumi(
    {
      external_id: o.external_id,
      record_revision: version,
      record: { id: Number(o.external_id), type: 1, name: 'Book', images: { large: url } },
    },
    { source: o.source, subjectId: CONTAINER },
    { converterRevision },
  );
}
function intents(count = 1, o = OWNER): MediaImportRequest[] {
  // Each asset fixture is an actual pure converter mediaImportIntent; no parallel wire schema.
  return Array.from(
    { length: count },
    (_, i) => conversion(o, count === 1 ? URL : `${URL}?asset=${i}`).mediaImportIntents[0]!,
  );
}
function receipt(n: number, containerId = CONTAINER): MediaImportAccepted {
  const value: MediaImportAccepted = { media: { id: uuid(n), containerId, purpose: 'cover', state: 'reserved' } };
  expect([...Errors(MediaImportAcceptedSchema, value)[1]]).toEqual([]);
  return value;
}
function snapshot(
  request: MediaImportRequest,
  accepted: MediaImportAccepted,
  state: MediaImportStatus['media']['state'],
): MediaImportStatus {
  const measured = state === 'uploaded' || state === 'available';
  const value = {
    media: {
      ...accepted.media,
      state,
      credit: request.credit,
      provenance: request.provenance,
      byteCount: measured ? 123 : null,
      mediaType: measured ? 'image/webp' : null,
      sha256: measured ? 'b'.repeat(64) : null,
      ...(state === 'rejected' ? { rejection: { code: 'source-denied' } } : {}),
    },
  } as MediaImportStatus;
  expect(checkMediaImportStatus(value)).toEqual([]);
  return value;
}
type Job = { bytes: string; key: string; request: MediaImportRequest; accepted: MediaImportAccepted };
type Measurement = { name: string; cost: GrowthSample['cost'] };
const fault = new Error('injected boundary failure');
class Harness {
  db!: Database;
  probe!: ReturnType<typeof createSqliteProbe>;
  store!: RecordBindings;
  resolver!: MediaResolver;
  owner = OWNER;
  assets = intents();
  signal = new AbortController().signal;
  jobs = new Map<string, Job>(); // Remote receipts only; durable local state is real SQLite.
  posts: Job[] = [];
  reads: string[] = [];
  fences: Parameters<MediaFencePort['fence']>[0][] = [];
  waits: number[] = [];
  events: string[] = [];
  measurements: Measurement[] = [];
  activeNetwork = 0;
  peakNetwork = 0;
  state: MediaImportStatus['media']['state'] = 'available';
  fenceReply: Awaited<ReturnType<MediaFencePort['fence']>> = { fenced: false, securityRevision: null };
  fenceError: unknown;
  beforeAccept = false;
  afterAccept = false;
  postReply = (job: Job): { status: number; body: unknown } => ({ status: 202, body: job.accepted });
  statusReply = async (job: Job): Promise<{ status: number; body: unknown }> => ({
    status: 200,
    body: snapshot(job.request, job.accepted, this.state),
  });
  constructor(
    readonly path: string,
    readonly factory: CreateMediaResolver,
  ) {
    this.reopen();
  }
  reopen(options: Partial<Pick<MediaResolverOptions, 'pollAttempts' | 'pollDelayMs'>> = {}, fresh = false) {
    if (this.db) {
      this.store.close();
      this.db.close();
    }
    if (fresh) rmSync(this.path, { force: true });
    this.db = new Database(this.path, { create: true });
    this.probe = createSqliteProbe(this.db, { growingTables: ['binding_records', 'binding_media'] });
    this.store = new RecordBindings(this.probe.database);
    const methods = new Set(['claim', 'mediaPending', 'prepareMedia', 'acceptMedia', 'observeMedia']);
    const bindings = new Proxy(this.store, {
      get: (target, name) => {
        if (typeof name !== 'string' || !methods.has(name))
          throw new Error(`Unexpected binding operation: ${String(name)}`);
        return (...args: unknown[]) => {
          this.events.push(name);
          if (name === 'acceptMedia' && this.beforeAccept) throw fault;
          const method = Reflect.get(target, name) as (...args: unknown[]) => unknown;
          const measured = this.probe.measure(() => method.apply(target, args));
          expect(measured.cost.blocks).toBe(0); // Buffer counters unavailable, not evidence of zero IO.
          expect(measured.cost.statements).toBe(measured.statements.length);
          expect(measured.cost.rows).toBe(measured.statements.reduce((n, s) => n + s.rows, 0));
          this.measurements.push({ name, cost: measured.cost });
          if (name === 'acceptMedia' && this.afterAccept) throw fault;
          return measured.value;
        };
      },
    });
    const remote: MediaFencePort = {
      fence: async (tuple, signal) => {
        expect(signal).toBe(this.signal);
        this.events.push('fence');
        this.fences.push(tuple);
        if (this.fenceError) throw this.fenceError;
        return this.fenceReply;
      },
      request: async (bytes, key, signal) => {
        expect(signal).toBe(this.signal);
        expect(signal.aborted).toBe(false);
        expect(Buffer.byteLength(bytes)).toBeLessThanOrEqual(65536);
        const request = JSON.parse(bytes) as MediaImportRequest;
        expect(checkMediaImportRequest(request)).toEqual([]);
        const journal = this.store.mediaPending(this.owner, key);
        expect(journal).toMatchObject({ key, bytes, accepted: null });
        expect(Buffer.byteLength(key)).toBeLessThanOrEqual(255);
        expect(key.startsWith(`${this.owner.source}:${this.owner.external_id}:`)).toBe(true);
        expect(key).toMatch(/[a-f0-9]{64}$/);
        expect(this.fences.length).toBeGreaterThan(0);
        const prior = this.jobs.get(key);
        if (prior) expect(bytes).toBe(prior.bytes);
        const job = prior ?? { bytes, key, request, accepted: receipt(100 + this.jobs.size, request.containerId) };
        this.jobs.set(key, job);
        this.posts.push(job);
        this.events.push('POST');
        return this.postReply(job);
      },
      status: async (id, signal) => {
        expect(signal).toBe(this.signal);
        expect(signal.aborted).toBe(false);
        const job = [...this.jobs.values()].find((job) => job.accepted.media.id === id);
        expect(job).toBeDefined();
        expect(this.store.mediaPending(this.owner, job!.key)?.accepted).toEqual(job!.accepted);
        this.reads.push(id);
        this.events.push('GET');
        return this.statusReply(job!);
      },
    };
    const port: MediaFencePort = {
      fence: (...args) => this.network(() => remote.fence(...args)),
      request: (...args) => this.network(() => remote.request(...args)),
      status: (...args) => this.network(() => remote.status(...args)),
    };
    this.resolver = this.factory({
      bindings,
      port,
      sleep: async (ms, signal) => {
        expect(signal).toBe(this.signal);
        expect(ms).toBeGreaterThanOrEqual(0);
        expect(ms).toBeLessThanOrEqual(1000);
        this.waits.push(ms);
      },
      ...options,
    });
  }
  bind(o = this.owner) {
    const output = convertBangumi(
      {
        external_id: o.external_id,
        record_revision: null,
        record: { id: Number(o.external_id), type: 1, name: 'Book' },
      },
      { source: o.source },
    );
    const request = {
      commands: output.proposals.map((command) => ({ ...command, key: `${o.source}:${o.external_id}:fixture-create` })),
    };
    const journal = this.store.prepare(o, output.converter_revision, request);
    this.store.acknowledge(o, journal.key, {
      results: [{ key: journal.key, status: 201, value: { id: CONTAINER, revision: 1 } }],
    });
  }
  run() {
    return this.resolver.resolve({
      owner: this.owner,
      containerId: CONTAINER,
      mediaImportIntents: this.assets,
      signal: this.signal,
    });
  }
  close() {
    this.store.close();
    this.db.close();
  }
  async network<T>(operation: () => Promise<T>): Promise<T> {
    this.activeNetwork++;
    this.peakNetwork = Math.max(this.peakNetwork, this.activeNetwork);
    try {
      await Promise.resolve();
      return await operation();
    } finally {
      this.activeNetwork--;
    }
  }
  resetCalls() {
    this.posts = [];
    this.reads = [];
    this.fences = [];
    this.waits = [];
    this.events = [];
    this.measurements = [];
    this.peakNetwork = 0;
  }
  checkPlans() {
    const evidence = this.probe.verifyPlans();
    expect(evidence.length).toBeGreaterThan(0);
    for (const statement of evidence.filter((s) => s.kind === 'read' || s.kind === 'write')) {
      expect(statement.plan.some((p) => /^SEARCH\b/.test(p.detail))).toBe(true);
      for (const p of statement.plan.filter((p) => /^SEARCH\b/.test(p.detail))) {
        expect(p.detail).toMatch(/source=\? AND external_id=\?/);
        if (/binding_media/.test(p.detail)) expect(p.detail).toContain('key=?');
      }
      expect(statement.sql).not.toMatch(/\b(?:OFFSET|COUNT\s*\()/i);
    }
  }
}
async function harness(run: (h: Harness) => Promise<void>) {
  const factory = await loadMediaResolver(); // Every outcome is red for this exact missing production binding.
  expect(typeof factory).toBe('function');
  const directory = mkdtempSync(join(tmpdir(), 'import-media-resolver-'));
  const h = new Harness(resolve(directory, 'bindings.sqlite'), factory);
  const network = spyOn(globalThis, 'fetch').mockImplementation((() => {
    throw new Error('Unexpected image or out-of-port network');
  }) as unknown as typeof fetch);
  try {
    h.bind();
    await run(h);
    expect(network).not.toHaveBeenCalled();
  } finally {
    network.mockRestore();
    h.close();
    rmSync(directory, { recursive: true, force: true });
  }
}
function resolved(value: MediaResolution) {
  expect(value.outcome).toBe('resolved');
  if (value.outcome !== 'resolved') throw new Error('Expected resolved media result');
  return value;
}
function empty(value: MediaResolution) {
  expect(value.mediaIds).toEqual({});
}
async function failure(h: Harness) {
  const before = { posts: h.posts.length, reads: h.reads.length, fences: h.fences.length };
  await expect(h.run()).rejects.toBeDefined();
  expect(h.posts.length - before.posts).toBeLessThanOrEqual(Math.min(h.assets.length, 64));
  expect(h.reads.length - before.reads).toBeLessThanOrEqual(Math.min(h.assets.length, 64) * 5);
  expect(h.fences.length - before.fences).toBeLessThanOrEqual(1);
}
function seed(h: Harness, count: number) {
  for (let i = 0; i < count; i++) {
    const o = { source: OWNER.source, external_id: String(1000 + i) };
    h.bind(o);
    for (let version = 0; version < 2; version++) {
      const request = conversion(o, URL, `native:${version}`).mediaImportIntents[0]!;
      const key = `${o.source}:${o.external_id}:seed:${version}`;
      h.store.prepareMedia(o, key, `seed-${version}`, request);
      const accepted = receipt(10000 + i * 2 + version);
      h.store.acceptMedia(o, key, accepted);
      h.store.observeMedia(o, key, snapshot(request, accepted, 'available'));
    }
  }
}

