// Fetches the shadcn registry for the style in components.json, writes the snapshot (shadcn-registry.json) and
// regenerates SHADCN.md from it. `bun scripts/shadcn-index.ts` refreshes both from the network;
// `bun scripts/shadcn-index.ts --offline` regenerates SHADCN.md from the committed snapshot alone.
import { join } from 'node:path';

const root = join(import.meta.dir, '..');
const snapshotPath = join(root, 'shadcn-registry.json');
const indexPath = join(root, 'SHADCN.md');

export type RegistryItem = {
  name: string;
  type: string;
  title?: string;
  description?: string;
  categories?: string[];
  files?: string[];
};
export type Snapshot = { source: string; style: string; items: RegistryItem[] };

type Section = { type: string; heading: string; lead: string };

const sections: Section[] = [
  {
    type: 'registry:ui',
    heading: 'Components',
    lead: 'Cloned into `src/shadcn/` by `shadcn add`. Import them as `@rezics/ui/shadcn/<name>`.',
  },
  {
    type: 'registry:block',
    heading: 'Blocks',
    lead: 'Whole page sections and example pages built from the components.',
  },
  { type: 'registry:hook', heading: 'Hooks', lead: 'Cloned into `src/hooks/`.' },
  { type: 'registry:lib', heading: 'Library items', lead: 'Cloned into `src/lib/`, or the utility alias.' },
  { type: 'registry:component', heading: 'Shared example parts', lead: 'Support code the examples import.' },
  { type: 'registry:example', heading: 'Examples', lead: 'One usage example per component.' },
  { type: 'registry:style', heading: 'Style items', lead: 'The style itself; `shadcn init` applies them.' },
  {
    type: 'registry:font',
    heading: 'Fonts',
    lead: 'Font presets `shadcn init` offers; Rezics sets its own fonts in `src/styles.css`.',
  },
];

// Items whose registry entry and documentation page carry no description, or whose page describes another item.
const purposes: Record<string, string> = {
  form: 'A form wrapper with no files in this style; compose forms from `field` instead',
  sonner: 'Toast notifications through the Sonner library; the Base UI `toast` replaces it and is the one cloned',
  attachment: 'A file or media attachment with a preview, title, description, actions and an upload state',
  bubble: 'A chat bubble with variants, alignment and reactions',
  marker: 'A labelled line with an optional icon, separator or border, such as a divider in a conversation',
  message: 'A conversation message layout with avatar, header, content and footer',
  'message-scroller': 'A scrolling message list with a button that jumps to its start or end',
  utils: 'The `cn` class-name helper that components import',
  'use-mobile': 'A hook reporting whether the viewport is below the mobile breakpoint, used by `sidebar`',
  'use-highlighted-code': 'A hook that highlights code with Shiki while it streams, used by `code-block`',
  example: 'The wrapper that lays out the registry examples',
  index: 'The style base: dependencies, the animation and variant layer, and the base CSS rules',
  style: 'The style definition: its dependencies and base CSS rules',
};

function purpose(item: RegistryItem): string {
  const given = purposes[item.name] ?? item.description?.trim();
  const title = item.title?.trim();
  const text =
    given ||
    (item.type === 'registry:example' && title
      ? `An example of the ${title} component in use`
      : item.type === 'registry:font' && title
        ? `The ${title} typeface`
        : item.type === 'registry:block' && title
          ? `The ${title} page, showing the components together`
          : title);
  if (!text) throw new Error(`${item.name} has no description; add it to the purposes table in shadcn-index.ts`);
  const line = text.replace(/\s+/g, ' ').trim();
  return /[.!?]$/.test(line) ? line : `${line}.`;
}

/** Renders SHADCN.md from a registry snapshot: one line per item, with its purpose and add command. */
export function renderIndex(snapshot: Snapshot): string {
  const lines = [
    '# shadcn capabilities',
    '',
    `Every item in the shadcn \`${snapshot.style}\` registry (${snapshot.items.length} items), one line each: what it is for and`,
    'the command that adds it. Run the commands from `packages/ui` or `apps/web`; both write into `packages/ui`.',
    'Look an interface piece up here before building it, and add it from shadcn when it exists.',
    '',
    'Generated by `scripts/shadcn-index.ts` from `shadcn-registry.json`; do not edit it by hand.',
    `The snapshot comes from ${snapshot.source}.`,
    'The registry has no separate chart items in this style: charts are the `chart` component, built on Recharts.',
    'Every component is cloned except `sonner`, which the Base UI `toast` replaces, and `form`, which has no files.',
  ];
  const known = new Set(sections.map((section) => section.type));
  for (const item of snapshot.items)
    if (!known.has(item.type)) throw new Error(`${item.name}: unknown type ${item.type}`);
  for (const section of sections) {
    const items = snapshot.items.filter((item) => item.type === section.type);
    if (items.length === 0) continue;
    lines.push('', `## ${section.heading} (${items.length})`, '', section.lead, '');
    for (const item of items)
      lines.push(`- \`${item.name}\` — ${purpose(item)} \`bunx shadcn@latest add ${item.name}\``);
  }
  return `${lines.join('\n')}\n`;
}

type Remote = {
  name: string;
  type: string;
  title?: string;
  description?: string;
  categories?: string[];
  files?: { path: string }[];
  meta?: { links?: { docs?: string; base?: { docs?: string } } };
};

async function describe(item: Remote): Promise<string | undefined> {
  const docs = item.meta?.links?.docs ?? item.meta?.links?.base?.docs;
  if (item.type !== 'registry:ui' || !docs) return undefined;
  const response = await fetch(`${docs}.md`);
  if (!response.ok) return undefined;
  return (await response.text()).match(/^description:\s*(.+)$/m)?.[1]?.trim();
}

async function fetchSnapshot(style: string): Promise<Snapshot> {
  const source = `https://ui.shadcn.com/r/styles/${style}/registry.json`;
  const response = await fetch(source);
  if (!response.ok) throw new Error(`${source}: ${response.status}`);
  const registry = (await response.json()) as { items: Remote[] };
  const items: RegistryItem[] = [];
  for (let start = 0; start < registry.items.length; start += 16) {
    const batch = registry.items.slice(start, start + 16);
    const described = await Promise.all(batch.map((item) => item.description ?? describe(item)));
    batch.forEach((item, index) => {
      const entry: RegistryItem = { name: item.name, type: item.type };
      if (item.title) entry.title = item.title;
      if (described[index]) entry.description = described[index]!;
      if (item.categories) entry.categories = item.categories;
      if (item.files?.length) entry.files = item.files.map((file) => file.path);
      items.push(entry);
    });
  }
  return { source, style, items };
}

if (import.meta.main) {
  let snapshot: Snapshot;
  if (process.argv.includes('--offline')) {
    snapshot = (await Bun.file(snapshotPath).json()) as Snapshot;
  } else {
    const { style } = (await Bun.file(join(root, 'components.json')).json()) as { style: string };
    snapshot = await fetchSnapshot(style);
    await Bun.write(snapshotPath, `${JSON.stringify(snapshot, null, 2)}\n`);
  }
  await Bun.write(indexPath, renderIndex(snapshot));
  console.log(`${snapshot.items.length} items indexed from ${snapshot.source}`);
}
