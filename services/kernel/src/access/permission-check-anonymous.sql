-- With no actor, principal, assignment or membership keys the grant and denial probes have no operands.
-- Keep the ordinary decision projection, including NULL for branches absent from this request.
WITH input AS MATERIALIZED (
 SELECT :resource_ids::uuid[] AS ids, :include_global::boolean AS include_global,
   COALESCE(:include_public::nullable(boolean), false) AS include_public,
   COALESCE(:policy_core::nullable(boolean), false) AS policy_core,
   COALESCE(:floor::nullable(boolean), false) AS floor, :deadline::timestamptz AS deadline
), authority AS MATERIALIZED (
 SELECT COALESCE(NULLIF(:at::nullable(text), '')::timestamptz, transaction_timestamp()) AS at,
        clock_timestamp() AS observed_at
)
SELECT id::text AS "resourceId",
       CASE WHEN NOT i.policy_core THEN t.observed_at < i.deadline AND i.floor END AS allowed,
       false AS "governanceReach",
       CASE WHEN NOT i.policy_core THEN false END AS explicit,
       CASE WHEN NOT i.policy_core THEN i.include_public AND t.observed_at < i.deadline END AS "publicAllowed",
       true AS "assignmentValid", t.observed_at < i.deadline AS "deadlineLive",
       false AS "localDenied",
       false AS "actorActionGrant",
       false AS "actorResourceRoleGrant",
       false AS "actorOwnAccountGrant",
       false AS "actorAuthenticatedBenefitGrant",
       false AS "principalActionGrant",
       false AS "principalResourceRoleGrant",
       false AS "principalOwnAccountGrant",
       false AS "principalAuthenticatedBenefitGrant",
       CASE WHEN i.include_global THEN false END AS "globalDenied",
       CASE WHEN i.include_global THEN false END AS "globalActorActionGrant",
       CASE WHEN i.include_global THEN false END AS "globalActorResourceRoleGrant",
       CASE WHEN i.include_global THEN false END AS "globalActorOwnAccountGrant",
       CASE WHEN i.include_global THEN false END AS "globalActorAuthenticatedBenefitGrant",
       CASE WHEN i.include_global THEN false END AS "globalPrincipalActionGrant",
       CASE WHEN i.include_global THEN false END AS "globalPrincipalResourceRoleGrant",
       CASE WHEN i.include_global THEN false END AS "globalPrincipalOwnAccountGrant",
       CASE WHEN i.include_global THEN false END AS "globalPrincipalAuthenticatedBenefitGrant",
       NULL::boolean AS "explicitLocalDenied",
       NULL::boolean AS "explicitActorActionGrant",
       NULL::boolean AS "explicitActorResourceRoleGrant",
       NULL::boolean AS "explicitActorOwnAccountGrant",
       NULL::boolean AS "explicitActorAuthenticatedBenefitGrant",
       NULL::boolean AS "explicitPrincipalActionGrant",
       NULL::boolean AS "explicitPrincipalResourceRoleGrant",
       NULL::boolean AS "explicitPrincipalOwnAccountGrant",
       NULL::boolean AS "explicitPrincipalAuthenticatedBenefitGrant",
       NULL::boolean AS "explicitGlobalDenied",
       NULL::boolean AS "explicitGlobalActorActionGrant",
       NULL::boolean AS "explicitGlobalActorResourceRoleGrant",
       NULL::boolean AS "explicitGlobalActorOwnAccountGrant",
       NULL::boolean AS "explicitGlobalActorAuthenticatedBenefitGrant",
       NULL::boolean AS "explicitGlobalPrincipalActionGrant",
       NULL::boolean AS "explicitGlobalPrincipalResourceRoleGrant",
       NULL::boolean AS "explicitGlobalPrincipalOwnAccountGrant",
       NULL::boolean AS "explicitGlobalPrincipalAuthenticatedBenefitGrant",
       t.at::text AS at, t.observed_at < i.deadline AS live
FROM input i CROSS JOIN authority t CROSS JOIN LATERAL (SELECT DISTINCT id FROM unnest(i.ids) id) target;
