export function classifyEvent(type: string): EventClassification {
  if (!Object.hasOwn(EVENT_CLASSIFICATIONS, type)) throw new TypeError('Unclassified history event type');
  return EVENT_CLASSIFICATIONS[type as keyof typeof EVENT_CLASSIFICATIONS];
}

export function assertEventClassifications(types: Iterable<string>): void {
  for (const type of types) classifyEvent(type);
}
