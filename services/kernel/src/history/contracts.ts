/** Stored role bits: append new powers of two; never reuse or renumber a bit. */
export const ACCOUNT_ROLE_BITS = Object.freeze({
  principal: 1,
  actor: 2,
  'acting-human': 4,
  delegate: 8,
  operator: 16,
  subject: 32,
  'durable-initiator': 64,
  reporter: 128,
  author: 256,
  member: 512,
  buyer: 1024,
  creator: 2048,
  reviewer: 4096,
  owner: 8192,
  uploader: 16384,
  appellant: 32768,
  voter: 65536,
  'related-party': 131072,
});
export type AccountRole = keyof typeof ACCOUNT_ROLE_BITS;
export const ACCOUNT_ROLES = Object.freeze(Object.keys(ACCOUNT_ROLE_BITS) as AccountRole[]);
export const ALL_ACCOUNT_ROLES = 262143;

export function validateRoleMask(value: unknown, allowed = ALL_ACCOUNT_ROLES): number {
  if (
    typeof value !== 'number' ||
    !Number.isInteger(value) ||
    value < 0 ||
    value > ALL_ACCOUNT_ROLES ||
    (value & allowed) !== value
  )
    throw new TypeError('Invalid account role mask');
  return value;
}

export function encodeRoles(roles: readonly AccountRole[]): number {
  if (!Array.isArray(roles) || roles.length > ACCOUNT_ROLES.length) throw new TypeError('Invalid account roles');
  return roles.reduce((mask, role) => {
    if (!Object.hasOwn(ACCOUNT_ROLE_BITS, role)) throw new TypeError('Unknown account role');
    return mask | ACCOUNT_ROLE_BITS[role as AccountRole];
  }, 0);
}

export function decodeRoles(mask: number): readonly AccountRole[] {
  validateRoleMask(mask);
  return ACCOUNT_ROLES.filter((role) => (mask & ACCOUNT_ROLE_BITS[role]) !== 0);
}

function artifact(skeletonFields: readonly string[]) {
  // Arbitrary owner response/event/work payloads can carry any inventory role.
  return Object.freeze({ minimizerVersion: 1, skeletonFields: Object.freeze(skeletonFields), roles: ACCOUNT_ROLES });
}

