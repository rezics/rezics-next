import { DBOS } from '@dbos-inc/dbos-sdk';
import { createAccess } from '../../../src/access/index.ts';
import { createCommerceCommands } from '../../../src/commerce/commands.ts';
import { readCommerceWorkerConfig } from '../../../src/commerce/config.ts';
import type { CheckoutSnapshot, StripeEventRef } from '../../../src/commerce/model.ts';
import { createStripePort } from '../../../src/commerce/stripe.ts';
import { createPool } from '../../../src/database/pool.ts';
import { createWorkClient } from '../../../src/work/client.ts';
import { composeWork } from '../../../src/work/registry.ts';
import clockQuery from '../../../src/commerce/work-clock.sql';
import type { Boundary, Control, Notice } from './refresh-user-fixture.ts';

// The pre-combined production event/child graph and names. Real SDK checkpoints and native command
// receipts are generated by this binary, then recovered by the actual default worker binary.
const gates = new Map<string, { token: string; release: PromiseWithResolvers<void> }>();
const releases = new Map<string, () => void>();
const send = (notice: Notice) => process.send?.({ ...notice, pid: process.pid });
process.on('message', (message: Control) => {
  if (message.kind === 'release') releases.get(message.token)?.();
  else {
    const release = Promise.withResolvers<void>();
    gates.set(`${message.workflow}/${message.point}`, { token: message.token, release });
    releases.set(message.token, release.resolve);
    send({ kind: 'armed', token: message.token });
  }
});
async function boundary(point: Boundary) {
  const workflow = DBOS.workflowID!;
  const gate = gates.get(`${workflow}/${point}`);
  if (!gate) return;
  gates.delete(`${workflow}/${point}`);
  send({ kind: 'boundary', workflow, point, token: gate.token });
  await gate.release.promise;
}
const config = readCommerceWorkerConfig(process.env)!;
const stripe = createStripePort({
  ...config.stripe,
  maxNetworkRetries: 0,
  clock: () => new Date(process.env.REFRESH_TIME!),
});
const pool = createPool(process.env.DATABASE_URL!);
const client = await createWorkClient(process.env.DATABASE_URL!);
const worker = await composeWork(
  [
    {
      name: 'commerce',
      register() {
        const commands = createCommerceCommands({ pool, access: createAccess({ actions: new Map() }) });
        const resolve = DBOS.registerStep(
          async (ref: StripeEventRef) =>
            ref.sessionId ?? (ref.paymentIntentId ? stripe.findCheckoutSession(ref.paymentIntentId) : null),
          { name: 'commerce.resolveCheckout' },
        );
        const clock = DBOS.registerStep(
          async () => (await clockQuery.run({ query: pool.query.bind(pool) }))!.observedAt,
          { name: 'commerce.clock' },
        );
        const read = DBOS.registerStep(
          async (sessionId: string, observedAt: string): Promise<CheckoutSnapshot> => ({
            ...(await stripe.readCheckout(sessionId)),
            observedAt,
          }),
          { name: 'commerce.readCheckout' },
        );
        const apply = DBOS.registerStep(
          async (snapshot: CheckoutSnapshot, workflowId: string) => {
            await boundary('order-lock'); // Old full read has already checkpointed when apply is entered.
            await commands.applyCheckoutSnapshot(snapshot, `wf:${workflowId}`);
            await boundary('commit'); // Native receipt committed; DBOS acknowledgement deliberately pending.
          },
          { name: 'commerce.applyCheckout' },
        );
        const child = DBOS.registerWorkflow(
          async (sessionId: string) => {
            await apply(await read(sessionId, await clock()), DBOS.workflowID!);
          },
          { name: 'commerce.checkoutSync' },
        );
        DBOS.registerWorkflow(
          async (ref: StripeEventRef) => {
            const session = await resolve(ref);
            if (!session) return;
            const handle = await DBOS.startWorkflow(child, {
              workflowID: `checkout:${session}:${ref.eventId}`,
              workflowIDReusePolicy: 'return-existing',
              queueName: 'workflows',
            })(session);
            await handle.getResult();
          },
          { name: 'commerce.stripeEvent' },
        );
      },
    },
  ],
  { pool, client, databaseUrl: process.env.DATABASE_URL!, executorId: process.env.KERNEL_EXECUTOR_ID! },
);
await worker.launch();
for (const queue of await DBOS.listQueues()) await queue.setMinPollingIntervalMs(5);
send({ kind: 'ready' });
