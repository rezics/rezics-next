import { expect, test } from 'bun:test';
import { validateGrowthBaseline } from './growth-baseline.ts';

for (const format of ['note', 'message']) {
  const unrelatedResult = { name: `orphan ${format} growth check` };
  void unrelatedResult;
}

test('baseline validation recognizes check names generated by literal loop axes and conditional choices', () => {
  for (const [file, names] of [
    ['growth-bootstrap-governance.test.ts', ['governance bootstrap first', 'governance bootstrap no-op']],
    [
      'growth-durable-initiator.test.ts',
      ['retry and replay: other people consents', 'revoked replay: same person history delegations'],
    ],
    [
      'growth-operator-fencing.test.ts',
      ['first fence page: unrelated accounts', 'late fence page: completed and pending history'],
    ],
    [
      'growth-operator-reinstatement.test.ts',
      ['first operator reinstatement page', 'late operator reinstatement page'],
    ],
  ] as const) {
    for (const name of names)
      expect(() =>
        validateGrowthBaseline([{ name, file: `services/kernel/test/access/${file}`, reason: 'verification run' }]),
      ).not.toThrow();
  }
});

test('baseline validation rejects undeclared values in generated check names', () => {
  for (const name of ['governance bootstrap unknown', 'unknown governance bootstrap first'])
    expect(() =>
      validateGrowthBaseline([
        { name, file: 'services/kernel/test/access/growth-bootstrap-governance.test.ts', reason: 'verification run' },
      ]),
    ).toThrow('is not present');
  expect(() =>
    validateGrowthBaseline([
      {
        name: 'first fence page: unknown population',
        file: 'services/kernel/test/access/growth-operator-fencing.test.ts',
        reason: 'verification run',
      },
    ]),
  ).toThrow('is not present');
});

test('baseline validation accepts an Auth check defined outside the kernel workspace', () => {
  expect(() =>
    validateGrowthBaseline([
      {
        name: 'Auth current consent exact tuple',
        file: 'services/auth/test/growth-current-consent.test.ts',
        reason: 'verification run',
      },
    ]),
  ).not.toThrow();
});

test('baseline validation does not treat a generated name outside checkGrowth as a check', () => {
  const name = ['orphan', ' note growth check'].join('');
  const file = 'services/kernel/test/support/growth-baseline-generated.test.ts';
  expect(() => validateGrowthBaseline([{ name, file, reason: 'verification run' }])).toThrow(
    `Growth baseline entry ${name} is not present in ${file}`,
  );
});
