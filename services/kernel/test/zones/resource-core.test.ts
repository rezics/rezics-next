import { afterAll, beforeAll, expect, test } from 'bun:test';
import { randomUUID } from 'node:crypto';
import { newId, routeOf } from '../../src/route/route.ts';
import { GLOBAL_CONTEXT } from '../../src/semantic/definitions.ts';
import { createBody, day, problem, resourceFixture, type ResourceFixture } from './resource-fixture.ts';
let f: ResourceFixture;
beforeAll(async () => { f = await resourceFixture(); }, 120_000);
afterAll(async () => { await f?.close(); });
const path = (id: string) => `/v1/zones/${id}`;
test('Zone resource commands initialize real ownership and preserve receipted CAS and current admission', async () => {
  await f.available();
  const input = createBody();
  input.configuration.scope = [];
  const key = { 'idempotency-key': JSON.stringify(randomUUID()) };
  const before = await f.receipts();
  const made = await f.call('owner', 'POST', '/v1/zones', input, key);
  expect(made.status).toBe(201);
  const id = made.body.zone.id as string;
  expect(made.headers.get('etag')).toBe('"1"');
  expect((await f.call('owner', 'POST', '/v1/zones', input, key)).body).toEqual(made.body);
  expect(await f.receipts()).toBe(before + 1);
  expect((await f.events(id)).map(e => e.type)).toEqual(['com.rezics.zone.created.v1']);
  const grants = await f.db.admin.query('SELECT subject_id,grant_role FROM access.resource_role_grant WHERE route=$1 AND resource_id=$2', [routeOf(id),id]);
  expect(grants.rows).toContainEqual({ subject_id: f.accounts.owner, grant_role: 'semantic.zone.owner' });
  expect((await f.configuration(id)).body.configuration).toEqual(input.configuration);
  await f.grant(id,'editor','zone:configure');
  const changed = structuredClone(input.configuration);
  changed.labels.en = 'Resource edit';
  const editKey = { 'idempotency-key': JSON.stringify(randomUUID()), ...f.conditional('1') };
  const editBody = { configuration: changed, mounts: [] };
  const edit = await f.call('editor','PUT',`${path(id)}/configuration`,editBody,editKey);
  expect(edit.status).toBe(200);
  expect(edit.body.zone.revision).toBe('2');
  expect((await f.call('editor','PUT',`${path(id)}/configuration`,editBody,editKey)).body).toEqual(edit.body);
  expect((await f.call('owner','PUT',`${path(id)}/configuration`,editBody,f.conditional('1'))).status).toBe(412);
  const other = structuredClone(changed); other.labels.en = 'Different digest';
  expect((await f.call('editor','PUT',`${path(id)}/configuration`,{configuration:other,mounts:[]},editKey)).status).toBe(422);
  await f.revoke(id,'editor','zone:configure');
  expect((await f.call('editor','PUT',`${path(id)}/configuration`,editBody,editKey)).status).toBe(403);
  expect((await f.configuration(id)).body.zone.revision).toBe('2');
  const events = await f.events(id);
  expect(events.filter(e => e.type==='com.rezics.zone.configured.v1')).toHaveLength(1);
  expect(JSON.stringify(events)).not.toContain('Resource edit');
  const races = await Promise.all([f.call('owner','PUT',`${path(id)}/configuration`,editBody,f.conditional('2')),f.call('owner','PUT',`${path(id)}/configuration`,editBody,f.conditional('2'))]);
  expect(races.map(r=>r.status).sort()).toEqual([200,412]);
  await f.access.revoke({route:0,id:GLOBAL_CONTEXT},'owner','zone:create');
  expect((await f.call('owner','POST','/v1/zones',input,key)).status).toBe(403);
},180_000);
test('Zone metadata and own listing disclose only current allowed resources and delete restore use the owner window',async()=>{
  await f.available();
  const input=createBody(); input.configuration.scope=[];
  const zone=await f.create(input);
  const missing=await f.call('anonymous','GET',path(newId(0x7111)));
  const privateRead=await f.call('anonymous','GET',path(zone.id));
  expect(privateRead.status).toBe(404);
  expect(problem(privateRead.body)).toEqual(problem(missing.body));
  const published=await f.call('owner','POST',`${path(zone.id)}:publish`,{visibility:'unlisted'},f.conditional(zone.revision));
  expect(published.status).toBe(200);
  let revision=published.body.zone.revision as string;
  const publicRead=await f.call('anonymous','GET',path(zone.id));
  expect(publicRead.status).toBe(200);
  expect(Object.keys(publicRead.body.zone).sort()).toEqual(['appearance','id','labels','navigation','revision','visibility']);
  expect((await f.call('suspended','GET',path(zone.id))).status).toBe(403);
  expect((await f.call('other','GET',`${path(zone.id)}/configuration`)).status).toBe(403);
  expect((await f.call('anonymous','GET','/v1/zones')).status).toBe(401);
  const listed=await f.call('owner','GET','/v1/zones?limit=100');
  expect(listed.status).toBe(200);
  expect(listed.body.zones.some((z:{id:string})=>z.id===zone.id)).toBe(true);
  expect((await f.call('owner','GET','/v1/zones?limit=101')).status).toBe(400);
  const deleted=await f.call('owner','DELETE',path(zone.id),undefined,f.conditional(revision));
  expect(deleted.status).toBe(200); revision=deleted.body.zone.revision;
  expect((await f.call('owner','GET',path(zone.id))).status).toBe(404);
  expect((await f.raw(zone.id))!.configuration).toEqual(input.configuration);
  expect((await f.call('other','POST',`${path(zone.id)}:restore`,{},f.conditional(revision))).status).toBe(403);
  f.advance(30*day-1);
  const restored=await f.call('owner','POST',`${path(zone.id)}:restore`,{},f.conditional(revision));
  expect(restored.status).toBe(200); revision=restored.body.zone.revision;
  expect((await f.call('anonymous','GET',path(zone.id))).status).toBe(200);
  const again=await f.call('owner','DELETE',path(zone.id),undefined,f.conditional(revision));
  expect(again.status).toBe(200); revision=again.body.zone.revision;
  f.advance(30*day);
  const late=await f.call('owner','POST',`${path(zone.id)}:restore`,{},f.conditional(revision));
  expect(late.status).toBe(409);
  expect((await f.raw(zone.id))!.configuration).toEqual(input.configuration);
},180_000);
